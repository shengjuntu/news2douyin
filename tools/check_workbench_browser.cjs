const {chromium:playwright}=require('playwright-core');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const base=process.env.N2D_QA_URL,folder=process.env.N2D_QA_OUTPUT;
 const browser=await playwright.launch({executablePath:process.env.N2D_QA_CHROMIUM,args:['--no-sandbox','--disable-dev-shm-usage','--disable-gpu','--disable-software-rasterizer'],headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1050}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 let releaseFacets;
 const facetGate=new Promise(resolve=>{releaseFacets=resolve;});
 const facetPattern='**/api/radar/facets?*';
 await page.route(facetPattern,async route=>{await facetGate;await route.continue();});
 await page.goto(base+'/radar?source=local',{waitUntil:'domcontentloaded'});
 await page.locator('a.action-link', {hasText:'形成选题'}).first().waitFor();
 assert.equal(await page.locator('[data-radar]').getAttribute('data-facet-state'),'loading');
 assert.equal(await page.locator('[data-radar-stat=total]').innerText(),'…');
 releaseFacets();
 await page.waitForFunction(()=>document.querySelector('[data-radar]').dataset.facetState==='ready');
 assert.equal(await page.locator('[data-radar-stat=total]').innerText(),'4');
 await page.unroute(facetPattern);
 await page.route(facetPattern,route=>route.fulfill({status:503,contentType:'application/json',body:'{"detail":"QA temporary statistics failure"}'}));
 await page.reload({waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>document.querySelector('[data-radar]').dataset.facetState==='error');
 assert.equal(await page.locator('a.action-link', {hasText:'形成选题'}).count(),4);
 assert.equal(await page.locator('[data-radar-stat=total]').innerText(),'…');
 await page.unroute(facetPattern);
 await page.locator('[data-radar-facet-retry]').click();
 await page.waitForFunction(()=>document.querySelector('[data-radar]').dataset.facetState==='ready');
 await page.locator('[data-radar-view=network]').click();
 await page.locator('[data-network-canvas] canvas').first().waitFor();
 assert.equal(await page.locator('header nav>a').count(),4);
 await page.locator('[data-radar-view=list]').click();
 await page.screenshot({path:folder+'/radar.png',fullPage:true});
 await page.locator('a.action-link', {hasText:'形成选题'}).first().click();
 await page.locator('input[name=title]').fill('援助政策变化的背景与影响');
 await page.locator('textarea[name=angle]').fill('沿历史脉络解释变化，区分事实与未证实说法。');
 await page.getByRole('button',{name:'创建并进入选题'}).click();
 await page.waitForURL(/\/workbench\/topic_.*\/selection/);
 const key=new URL(page.url()).pathname.split('/')[2];
 await page.locator('#topic-selected .topic-card').first().waitFor();
 assert.match(await page.locator('#topic-title').inputValue(),/援助政策/);
 await page.locator('#topic-angle').fill('用三分钟梳理政策变化，明确每个判断的来源。');
 await page.getByRole('button',{name:'保存选题与范围'}).click();
 await page.waitForFunction(()=>!document.querySelector('#topic-dirty').textContent);
 await page.screenshot({path:folder+'/selection.png',fullPage:true});
 const fixture=await page.request.post(base+'/qa/complete-research/'+key);assert.equal(fixture.status(),200);
 await page.goto(base+'/workbench/'+key+'/research');
 await page.locator('#report-content section').first().waitFor();
 await page.screenshot({path:folder+'/research.png',fullPage:true});
 await page.getByRole('button',{name:'基于研究创建可编辑初稿'}).click();
 await page.waitForURL(/\/creation\?script=/);
 await page.locator('#segments-list .segment-card').first().waitFor();
 assert.match(await page.locator('#script-text').inputValue(),/特朗普/);
 await page.screenshot({path:folder+'/creation.png',fullPage:true});
 await page.locator('.work-stages a[href$="/works"]').click();
 assert.equal(await page.getByRole('link',{name:'下载报告'}).count(),1);
 await page.getByRole('button',{name:'标记本次工作已完成'}).click();
 await page.waitForFunction(()=>window.contentTask?.phase==='works');
 await page.goto(base+'/workbench?view=works');
 assert.equal(await page.getByRole('link',{name:'援助政策变化的背景与影响'}).count(),1);
 const profile=await page.request.post(base+'/api/profiles',{data:{name:'browser_demo',provider:'mock',extra:{filter_mode:'rules'}}});assert.equal(profile.status(),200);
 await page.goto(base+'/profiles?selected=browser_demo');
 await page.getByRole('button',{name:'正式采集入库',exact:true}).click();
 await page.waitForURL(/\/tasks\/[^/]+$/);
 const collection=new URL(page.url()).pathname.split('/')[2];
 let collected;
 for(let attempt=0;attempt<150;attempt++){
  collected=await (await page.request.get(base+'/api/tasks/'+collection)).json();
  if(['succeeded','failed','cancelled'].includes(collected.status))break;
  await page.waitForTimeout(100);
 }
 assert.equal(collected.status,'succeeded',collected.error_text);
 await page.goto(base+'/articles?task_id='+collection);
 assert.equal(await page.locator('table tr').count(),3);
 assert.equal(await page.getByText('演示数据',{exact:true}).count(),2);
 const focus=(await (await page.request.get(base+'/qa/focus')).json()).key;
 await page.goto(base+'/focus/'+focus);
 await page.locator('[data-knowledge-graph] [data-network-canvas] canvas').first().waitFor({state:'attached'});
 await page.screenshot({path:folder+'/focus.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 for(const url of ['/radar','/workbench','/focus/'+focus,'/workbench/'+key+'/selection']){
  await page.goto(base+url);await page.locator('main').waitFor();
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+3);
  assert.equal(overflow,false,'horizontal overflow at '+url);
 }
 await page.screenshot({path:folder+'/mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({ok:true,task:key,pages:['radar','selection','research','creation','works','focus','collection'],mobile:true,pageErrors:errors}));
 await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1;});
