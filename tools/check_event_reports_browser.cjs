  await card(config.ids.local).waitFor();await page.waitForTimeout(150);
  assert.equal(enrichRequests.length,name==='desktop'?0:1,'Page load unexpectedly enqueued source fetches');
  assert.equal((await(await page.request.get(base+'/qa/state')).json()).fetch,before.fetch);
  assert.equal(await card(config.ids.local).locator('h2').textContent(),config.local_title);
  assert.equal(await card(config.ids.cached).locator('h2').textContent(),config.cached_title);
  assert.equal(await card(config.ids.missing).locator('h2').textContent(),'报道内容待补充');
  assert(await card(config.ids.local).getByText(config.local_excerpt,{exact:true}).isVisible());
  assert((await card(config.ids.local).textContent()).includes('编码线索 ZUNI · 交战 · MOROCCO'));
  assert.equal(await card(config.ids.missing).getByRole('button',{name:'保留线索',exact:true}).count(),1);
  assert((await card(config.ids.missing).locator('[data-gdelt-content-status]').textContent()).includes('可重试'));
  await card(config.ids.missing).locator('[data-gdelt-select]').click();
