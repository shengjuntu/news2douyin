  assert(await page.locator('#gdelt-topic-title').getAttribute('required')!==null);
  await page.locator('#gdelt-select-close').click();
  const missingSelect=card(config.ids.missing).locator('[data-gdelt-select]');
  await missingSelect.evaluate(button=>{button.dataset.gdeltTitle='合成'.repeat(300);});
  await missingSelect.click();assert.equal((await page.locator('#gdelt-topic-title').inputValue()).length,240);
  await page.locator('#gdelt-select-close').click();await missingSelect.evaluate(button=>{button.dataset.gdeltTitle='';});
  results[name]={list_bounds:await bounds(name+' list'),missing_title_requires_input:true,long_selection_title_bounded:true,retry_state_visible:true};
  await page.screenshot({path:path.join(folder,'event-reports-list-'+name+'.png'),fullPage:true});
  await card(config.ids.cached).getByRole('button',{name:'中文译读',exact:true}).click();
