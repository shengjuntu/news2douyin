 page.on('requestfailed',r=>{if(r.failure()?.errorText!=='net::ERR_ABORTED')failed.push(r.url());});
 page.on('request',r=>{if(r.method()==='POST'&&r.url().endsWith('/api/gdelt/content/enrich'))enrichRequests.push(r.postDataJSON());if(r.method()==='POST'&&r.url().endsWith('/api/translations'))translationInputs.push(r.postDataJSON());});
